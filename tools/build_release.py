"""Package the release from a balance pilot whose in-game session passed.

Usage: python build_release.py <session_result_dir> [--pilot balance-pilot] --hemtt
           writes each patch to ../addons/<name>/ and ../release.json, for `hemtt build` / `hemtt release`
       python build_release.py <session_result_dir> [--pilot balance-pilot] [--out release]
           packs an unsigned release/@A3Balance without HEMTT
       python build_release.py --candidate <folder>   (unverified release candidate, for review only)
       python build_release.py --candidate - --hemtt  (the same, written into the HEMTT project)
The release patches are byte for byte the configs the pilot tested; only the tests addon stays out.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

from build_helmet_pilot import pack_files
from build_patch import PREFIX

MOD = "@A3Balance"
GENERATED = "Generated by tools/build_patch.py"
MAIN = f"""// A3 Balance core: version and name. Each mod's values are in its own addon, which loads only with that mod.
class CfgPatches
{{
    class {PREFIX}_main
    {{
        name = "A3 Balance";
        author = "A3 Balance";
        requiredVersion = 2.18;
        requiredAddons[] = {{}};
        units[] = {{}};
        weapons[] = {{}};
    }};
}};
"""


def verified(pilot_folder, session):
    manifest = json.loads((pilot_folder / "manifest.json").read_text())
    if session is not None:
        report = json.loads((session / "session-report.json").read_text())
        if not report["passed"] or report["pilot_build_id"] != manifest["build_id"]:
            raise ValueError("The session did not pass for this pilot build; no release is built")
    configs = {}
    for name, digest in manifest["config_sha256"].items():
        data = (pilot_folder / "source" / name / "config.cpp").read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"Pilot config {name} differs from its manifest")
        configs[name] = data
    return configs, manifest


def info(manifest, session, configs, **extra):
    return {"status": "verified in game" if session is not None else "CANDIDATE: not verified in game; do not distribute",
            "pilot_build_id": manifest["build_id"], "session": Path(session).name if session is not None else None, **extra,
            "addons": {f"{PREFIX}_{name}": {"config_sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data),
                                            "required_addons": manifest["addons"][name]["required_addons"]}
                       for name, data in configs.items()},
            "changed_fields": manifest["changed_fields"], "by_kind": manifest["by_kind"]}


def build(root, pilot_folder, out, session=None):
    configs, manifest = verified(pilot_folder, session)
    if out.exists():
        raise ValueError(f"{out} already exists; refusing to overwrite a release")
    mod = out / MOD
    (mod / "addons").mkdir(parents=True)
    hashes = {}
    for name, data in {"main": MAIN.encode(), **configs}.items():
        archive = pack_files([("config.cpp", data)], f"{PREFIX}_{name}")
        (mod / f"addons/{PREFIX}_{name}.pbo").write_bytes(archive)
        hashes[f"{PREFIX}_{name}"] = hashlib.sha256(archive).hexdigest()
    (mod / "mod.cpp").write_text('name = "A3 Balance";\ndescription = "Mod helmets, vests, uniforms and rifle ammunition on the vanilla ladder";\n', encoding="utf-8")
    (mod / "README.md").write_text((root / "release_README.md").read_text(encoding="utf-8"), encoding="utf-8")
    result = info(manifest, session, configs, pbo_sha256=hashes, signed=False)
    (out / "release.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


def write_hemtt(root, pilot_folder, session):
    """Write the verified patches into the HEMTT project; HEMTT builds and signs the PBOs."""
    configs, manifest = verified(pilot_folder, session)
    project = root.parent
    if not (project / ".hemtt/project.toml").exists():
        raise ValueError(f"No HEMTT project at {project}")
    addons = project / "addons"
    # Remove patches an earlier build generated that this one no longer has.
    for folder in addons.iterdir():
        config = folder / "config.cpp"
        if folder.name != "main" and folder.name not in configs and config.exists() and GENERATED in config.read_text(encoding="utf-8")[:300]:
            shutil.rmtree(folder)
    (addons / "main").mkdir(exist_ok=True)
    (addons / "main/config.cpp").write_text(MAIN, encoding="utf-8", newline="\n")
    for name, data in configs.items():
        folder = addons / name
        folder.mkdir(exist_ok=True)
        (folder / "config.cpp").write_bytes(data)
        (folder / "$PBOPREFIX$").write_text(f"z\\{PREFIX}\\addons\\{name}\n", encoding="utf-8", newline="\n")
    result = info(manifest, session, configs, built_with="hemtt")
    (project / "release.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("session", type=Path, nargs="?")
    parser.add_argument("--pilot", default="balance-pilot")
    parser.add_argument("--out", type=Path, default=Path("release"))
    parser.add_argument("--hemtt", action="store_true", help="write the patches into ../addons for HEMTT")
    parser.add_argument("--candidate", type=Path, help="build an unverified candidate into this folder instead")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    if (args.session is None) == (args.candidate is None):
        parser.error("give a passed session result directory, or --candidate <folder>")
    if args.hemtt:
        # With --candidate the patches go in marked as not verified in game (release.json says so).
        print(json.dumps(write_hemtt(root, root / args.pilot, None if args.candidate else args.session), indent=2))
    else:
        out = args.candidate if args.candidate else root / args.out
        print(json.dumps(build(root, root / args.pilot, out, None if args.candidate else args.session), indent=2))
